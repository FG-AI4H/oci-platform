/**
 * The Croissant 1.1 manifest of the workshop slice, and the public metadata
 * file its record set reads (#644).
 *
 * Both are built from a `Selection`, which has no reference label, so neither
 * can publish one. The record set carries exactly three fields: image id, sex
 * and age band.
 */

export type Json = Record<string, unknown>;

/** A file the profile hosts: name, bytes facts and media type. */
export interface HostedFile {
  name: string;
  encodingFormat: string;
  bytes: number;
  sha256: string;
  description?: string;
}

export const METADATA_HEADER = ['image_id', 'sex', 'age_band'] as const;

/** `image_id,sex,age_band`: the public record set. No label column, by type. */
export function metadataCsv(selection: Selection): string {
  return toCsv([
    [...METADATA_HEADER],
    ...selection.images.map((image) => [image.imageId, image.sex, image.ageBand]),
  ]);
}

export function distributionId(fileName: string): string {
  return uuid5(`${DATASET_SLUG}:dist:${fileName}`);
}

export function describeTextFile(name: string, content: string, description: string): HostedFile {
  const bytes = Buffer.from(content, 'utf8');
  return {
    name,
    encodingFormat: 'text/csv',
    bytes: bytes.length,
    sha256: sha256Hex(bytes),
    description,
  };
}

/** The image files as hosted. Refuses a selection whose files have not been prepared. */
export function hostedImages(selection: Selection): HostedFile[] {
  return selection.images.map((image) => {
    if (!image.hosted) {
      throw new Error(
        `${image.file} has not been prepared yet: run the fetch step before generating the manifest.`,
      );
    }
    return {
      name: image.file,
      encodingFormat: 'image/png',
      bytes: image.hosted.bytes,
      sha256: image.hosted.sha256,
    };
  });
}

function fileObject(file: HostedFile): Json {
  const id = distributionId(file.name);
  return {
    '@id': id,
    '@type': 'cr:FileObject',
    name: file.name,
    ...(file.description ? { description: file.description } : {}),
    encodingFormat: file.encodingFormat,
    contentUrl: `/v2/catalog/datasets/${DATASET_SLUG}/distributions/${id}/download`,
    contentSize: `${file.bytes} B`,
    sha256: file.sha256,
  };
}

function recordField(name: (typeof METADATA_HEADER)[number], description: string): Json {
  return {
    '@type': 'cr:Field',
    '@id': `images/${name}`,
    name,
    description,
    dataType: 'sc:Text',
    source: { fileObject: { '@id': distributionId(METADATA_FILE) }, extract: { column: name } },
  };
}

function labelProtocol(selection: Selection): Json {
  const scale = `0 = ${selection.finding.nameEn.toLowerCase()} absent; 1 = present`;
  switch (selection.labelSource) {
    case 'radiologist-adjudicated':
      return {
        version: 'Radiologist-adjudicated labels released for a subset of NIH ChestX-ray14',
        labelScale: scale,
        gradersPerItem: 3,
        adjudication: 'disagreements between the three readers were adjudicated',
        perRaterLabelsRetained: false,
      };
    case 'nih-report-mined':
      return {
        version: 'NIH ChestX-ray14 report-mined labels',
        labelScale: scale,
        gradersPerItem: 1,
        graderQualification:
          'none: the label was mined from the radiology report by text processing, not assigned by a reader of the image',
        perRaterLabelsRetained: false,
      };
    case 'synthetic-stand-in':
      return {
        version: 'Invented labels of the synthetic stand-in',
        labelScale: scale,
        gradersPerItem: 1,
        graderQualification: 'none: generated by a script',
        perRaterLabelsRetained: false,
      };
  }
}

/**
 * Build the manifest. `bundled` are the small files kept in the repository
 * (metadata and teaching files); the images come from the selection.
 */
export function buildManifest(selection: Selection, bundled: readonly HostedFile[]): Json {
  const preparedAt = `${selection.preparedOn}T00:00:00Z`;
  const slice = `${selection.images.length}-image slice of NIH ChestX-ray14, one image per patient, balanced by sex and age band, at most ${MAX_SIDE_PX} px on the longest side`;

  return {
    '@context': {
      '@vocab': 'https://schema.org/',
      sc: 'https://schema.org/',
      cr: 'http://mlcommons.org/croissant/',
      rai: 'http://mlcommons.org/croissant/RAI/',
      prov: 'http://www.w3.org/ns/prov#',
      odrl: 'http://www.w3.org/ns/odrl/2/',
      dct: 'http://purl.org/dc/terms/',
      bio: 'https://oci.ai4h.net/biocroissant/v0.1#',
    },
    '@type': 'sc:Dataset',
    // Croissant 1.1 only. The bio-prov profile is not claimed: at this access
    // tier it requires the de-identification METHOD of a de-identified
    // dataset, and what has been read of the source says that the images are
    // de-identified, not how. The PROV-O statements below are given anyway.
    'dct:conformsTo': 'http://mlcommons.org/croissant/1.1',
    name: datasetName(selection),
    description: datasetDescription(selection),
    // Attribution 1 of 3: the link to the source's download site.
    url: NIH_DOWNLOAD_PAGE,
    sameAs: NIH_PAPER_DOI,
    // The source publishes its terms in a README on its download site, not under a named licence.
    license: NIH_DOWNLOAD_PAGE,
    'dct:rights': termsStatement(selection),
    version: DATASET_VERSION,
    datePublished: selection.preparedOn,
    creator: [
      { '@type': 'sc:Organization', name: 'National Institutes of Health Clinical Center' },
    ],
    publisher: {
      '@type': 'sc:Organization',
      name: 'OCI Platform (GI-AI4H): workshop slice of NIH ChestX-ray14',
    },
    keywords: ['chest x-ray', 'radiology', 'binary finding', 'subgroup analysis', 'workshop'],
    // Attribution 2 of 3: the citation the source asks for.
    citeAs: NIH_CITATION_BIBTEX,
    // Attribution 3 of 3: the acknowledgement of the data provider.
    creditText: NIH_ACKNOWLEDGEMENT,
    distribution: [...bundled, ...hostedImages(selection)].map(fileObject),
    recordSet: [
      {
        '@type': 'cr:RecordSet',
        '@id': 'images',
        name: 'images',
        description:
          'One row per image of the slice. The reference label of the evaluation task is not part of this record set or of any distribution: it is held by the evaluation service.',
        key: 'images/image_id',
        field: [
          recordField(
            'image_id',
            'Identifier of the image: its file name without the extension. The item identifier of the evaluation task.',
          ),
          recordField('sex', 'Sex as recorded by the source: F or M.'),
          recordField('age_band', 'Age at the examination, as a band: 18-39, 40-59 or 60+.'),
        ],
      },
    ],
    'bio:imagingModality': [{ '@type': 'sc:DefinedTerm', name: 'X-ray' }],
    'bio:bodyRegion': [{ '@type': 'sc:DefinedTerm', name: 'Chest' }],
    'bio:anonymizationLevel': 'DEIDENTIFIED',
    ...(selection.standIn ? { 'bio:synthetic': true } : {}),
    'rai:dataCollection': `Selection rule: ${selection.rule}`,
    'rai:dataCollectionTimeframe': `Slice prepared on ${selection.preparedOn}`,
    'rai:dataAnnotationProtocol': labelSourceSentence(selection),
    'rai:personalSensitiveInformation':
      'Sex and age band are published per image. Age in years, the patient identifier and every other column of the source metadata are left out.',
    'bio:labelProtocol': labelProtocol(selection),
    'prov:wasDerivedFrom': {
      '@type': 'prov:Entity',
      '@id': NIH_PAPER_DOI,
      name: 'NIH ChestX-ray14 (ChestX-ray8), Wang et al., 2017',
    },
    'prov:wasGeneratedBy': [
      {
        '@type': ['prov:Activity', 'https://w3id.org/dpv/ai#DataCollection'],
        '@id': '#activity-workshop-slice-v1',
        name: `Selection of a ${slice}`,
        'prov:startedAtTime': preparedAt,
        'prov:endedAtTime': preparedAt,
        'prov:used': NIH_PAPER_DOI,
        'prov:wasAssociatedWith': {
          '@type': 'prov:SoftwareAgent',
          name: 'oci-platform scripts/radiology-workshop',
          'prov:actedOnBehalfOf': { '@type': 'prov:Organization', name: 'OCI Platform (GI-AI4H)' },
        },
      },
      {
        '@type': ['prov:Activity', 'https://w3id.org/dpv/ai#DataLabelling'],
        '@id': '#activity-reference-labels',
        name: 'Reference labels of the evaluation task (not published)',
        'prov:used': {
          '@type': 'prov:Entity',
          '@id': '#guideline-reference-labels',
          name: String(labelProtocol(selection)['version']),
          version: '1',
        },
        'prov:wasAssociatedWith': [
          {
            '@type':
              selection.labelSource === 'radiologist-adjudicated'
                ? 'prov:Person'
                : 'prov:SoftwareAgent',
            'prov:hadRole': 'Annotator',
          },
        ],
      },
    ],
    'prov:wasAttributedTo': [
      {
        '@type': 'prov:Organization',
        name: 'National Institutes of Health Clinical Center (data provider)',
      },
      {
        '@type': 'prov:Organization',
        name: 'OCI Platform (GI-AI4H): re-publisher of the workshop slice',
      },
    ],
    'odrl:hasOffer': {
      '@type': 'odrl:Offer',
      '@id': '#offer-source-terms',
      'odrl:permission': [
        {
          'odrl:action': ['odrl:use', 'odrl:distribute', 'odrl:derive'],
          'odrl:target': DATASET_SLUG,
          'odrl:duty': [{ 'odrl:action': 'odrl:attribute' }],
        },
      ],
    },
    'cr:consentCode': [
      {
        '@type': 'sc:DefinedTerm',
        '@id': 'http://purl.obolibrary.org/obo/DUO_0000004',
        termCode: 'DUO_0000004',
        name: 'no restriction',
        inDefinedTermSet: 'http://purl.obolibrary.org/obo/duo.owl',
      },
    ],
  };
}

