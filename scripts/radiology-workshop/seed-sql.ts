/**
 * The SQL of the `radiology-workshop` seed profile (#644), generated from the
 * selection, the hidden labels and the manifest. Same conventions as
 * `seed/demo.sql`: every statement can be replayed, a second run changes no
 * row, and the answer key is never overwritten.
 */

/** A single-quoted SQL string literal. */
function text(value: string): string {
  return `'${value.replaceAll("'", "''")}'`;
}

/** A dollar-quoted literal, for text that is full of quotes (JSON, Markdown). */
function dollar(tag: string, value: string): string {
  const quote = `$${tag}$`;
  if (value.includes(quote)) throw new Error(`the text contains the dollar-quote tag ${quote}`);
  return `${quote}${value}${quote}`;
}

function nullable(value: string | null): string {
  return value === null ? 'NULL' : text(value);
}

/** Same rule as the API: the first 16 hex characters of the sha256 of the Markdown. */
export function instructionsVersion(markdown: string): string {
  return createHash('sha256').update(markdown, 'utf8').digest('hex').slice(0, 16);
}

function distributionRow(file: HostedFile): string {
  const id = distributionId(file.name);
  return [
    `    (${text(id)}::uuid, ver_id, ${text(id)},`,
    `     ${text(`/v2/catalog/datasets/${DATASET_SLUG}/distributions/${id}/download`)},`,
    `     ${text(file.encodingFormat)}, ${file.bytes}, ${text(file.sha256)},`,
    `     false, 'S3'::"catalog"."DistributionStorageBackend", bucket,`,
    `     ${text(`${DATASET_SLUG}/${id}/${file.name}`)}, 'READY'::"catalog"."DistributionUploadStatus")`,
  ].join('\n');
}

function modelCardRow(slug: string, card: ReturnType<typeof modelCards>['modelA' | 'modelB']) {
  const jurisdictions = card.trainingDataJurisdictions.map(text).join(', ');
  return [
    `    (${text(uuid5(`${PROFILE}:model-card:${slug}`))}::uuid, ${text(slug)},`,
    `     ${text(JSON.stringify(card.intendedUse))}::jsonb,`,
    `     ${text(card.modelClass)}, ${text(card.architectureSummary)}, ${text(card.version)},`,
    `     ARRAY[${jurisdictions}], false, ${text(card.status)}, ${text(card.modelDeveloper)}, ${text(card.developerContact)},`,
    `     ${text(card.clinicalSummary)},`,
    `     ${nullable(card.knownBiases)},`,
    `     ${nullable(card.ongoingMaintenance)}, now())`,
  ].join('\n');
}

export interface SeedSqlInput {
  selection: Selection;
  /** HIDDEN reference labels, by image id. They go into the answer key and nowhere else. */
  labels: ReadonlyMap<string, 0 | 1>;
  manifest: Json;
  /** Every hosted file: the bundled ones and the images. */
  files: readonly HostedFile[];
}

export function buildSeedSql({ selection, labels, manifest, files }: SeedSqlInput): string {
  const answerKey = Object.fromEntries(
    selection.images.map((image) => {
      const label = labels.get(image.imageId);
      if (label === undefined) throw new Error(`no reference label for ${image.imageId}`);
      return [image.imageId, label];
    }),
  );

  // #410: each item's sex and age band, the two subgroup fields of the task.
  // Public in the metadata file already; on the task they sit beside the
  // answer key, which is where the API reads them from when it scores.
  const subgroupValues = Object.fromEntries(
    selection.images.map((image) => [image.imageId, { sex: image.sex, ageBand: image.ageBand }]),
  );

  const instructions = campaignInstructionsFr(selection);
  const version = instructionsVersion(instructions);
  const cards = modelCards(selection);
  const workflow = JSON.stringify({
    nAnnotators: READERS_PER_IMAGE,
    taskTimeoutHours: TASK_TIMEOUT_HOURS,
  });

  return `-- ============================================================================
-- OCI Platform: seed profile \`${PROFILE}\` (#644).
-- Content for the December 2026 radiology workshop: a hosted chest X-ray
-- slice, one evaluation task, one annotation campaign and two model cards.
--
-- GENERATED by \`pnpm radiology-workshop generate\` from selection.json and
-- reference-labels.hidden.csv in this directory. Do not edit by hand:
-- change the inputs or scripts/radiology-workshop/ and regenerate.
${
  selection.standIn
    ? `--
-- SYNTHETIC STAND-IN. The images are procedurally generated placeholders and
-- the reference labels are invented. The migrate task refuses to seed a
-- stand-in on a deployed environment.
`
    : ''
}--
-- Replayed by apps/migrate after seed/demo.sql, only where OCI_SEED_PROFILES
-- lists this profile, never on prod. Same rules as demo.sql: every statement
-- can be replayed and a second run changes no row. The whole file is one
-- transaction, so a failure leaves nothing half-written.
-- ============================================================================

BEGIN;

-- ----------------------------------------------------------------------------
-- 1. Dataset, version and hosted files.
-- The repository is the authority for the manifest: dataset and version rows
-- refresh when it differs. File rows refresh their size and hash, because a
-- regenerated teaching file keeps its name and address.
-- Published on top (#738, same rule as demo.sql since #641): publishing a
-- version through the API rewrites the dataset row, so the dataset row stops
-- following the repository once the dataset has a version published by anyone
-- other than this file, which publishes as ${SEED_USER_ID}.
-- The version row this file wrote still follows the repository; a version row
-- published by anyone else is never rewritten, even under the same number.
-- The image bytes are NOT uploaded by the deploy: an operator uploads them
-- once, and the migrate task replays this file only after it has found every
-- one of them in the bucket.
-- ----------------------------------------------------------------------------

DO $workshop_dataset$
DECLARE
  ds_id   uuid;
  ver_id  uuid;
  bucket  text := COALESCE(NULLIF(current_setting('app.datasets_bucket', true), ''), 'oci-datasets-local');
  payload jsonb := ${dollar('manifest', JSON.stringify(manifest))}::jsonb;
BEGIN
  INSERT INTO "catalog"."datasets" (
    id, slug, name, description, host_id, visibility, status,
    access_tier, commercial_use_terms, modalities,
    conformance_version, croissant, duo_terms, updated_at
  ) VALUES (
    ${text(uuid5(`${DATASET_SLUG}:dataset`))}::uuid, ${text(DATASET_SLUG)},
    ${text(datasetName(selection))},
    ${text(datasetDescription(selection))},
    ${text(SEED_USER_ID)}, 'PUBLIC', 'PUBLISHED',
    'OPEN', 'OK', ARRAY['X-ray'],
    '1.1', payload, ARRAY['DUO_0000004']::text[], CURRENT_TIMESTAMP
  )
  ON CONFLICT (slug) DO UPDATE SET
    name = EXCLUDED.name,
    description = EXCLUDED.description,
    croissant = EXCLUDED.croissant,
    conformance_version = EXCLUDED.conformance_version,
    duo_terms = EXCLUDED.duo_terms,
    updated_at = CURRENT_TIMESTAMP
  WHERE "datasets".croissant IS DISTINCT FROM EXCLUDED.croissant
    -- Not once someone has published on top of the seed (#738).
    AND NOT EXISTS (
      SELECT 1 FROM "catalog"."dataset_versions" v
      WHERE v.dataset_id = "datasets".id
        AND v.published_by_id <> ${text(SEED_USER_ID)}
    );

  SELECT id INTO STRICT ds_id FROM "catalog"."datasets" WHERE slug = ${text(DATASET_SLUG)};

  INSERT INTO "catalog"."dataset_versions" (
    id, dataset_id, version, croissant, published_by_id, published_at
  ) VALUES (
    ${text(uuid5(`${DATASET_SLUG}:version:${DATASET_VERSION}`))}::uuid, ds_id, ${text(DATASET_VERSION)}, payload,
    ${text(SEED_USER_ID)}, CURRENT_TIMESTAMP
  )
  ON CONFLICT (dataset_id, version) DO UPDATE SET
    croissant = EXCLUDED.croissant
  WHERE "dataset_versions".croissant IS DISTINCT FROM EXCLUDED.croissant
    -- Only a version row this file wrote (#738).
    AND "dataset_versions".published_by_id = ${text(SEED_USER_ID)};

  SELECT id INTO STRICT ver_id FROM "catalog"."dataset_versions"
  WHERE dataset_id = ds_id AND version = ${text(DATASET_VERSION)};

  INSERT INTO "catalog"."distributions" (
    id, dataset_version_id, croissant_id, content_url, content_type,
    content_size_bytes, content_hash_sha256, requires_access,
    storage_backend, s3_bucket, s3_key, upload_status
  ) VALUES
${files.map(distributionRow).join(',\n')}
  ON CONFLICT (id) DO UPDATE SET
    content_size_bytes = EXCLUDED.content_size_bytes,
    content_hash_sha256 = EXCLUDED.content_hash_sha256
  WHERE ("distributions".content_size_bytes, "distributions".content_hash_sha256)
        IS DISTINCT FROM (EXCLUDED.content_size_bytes, EXCLUDED.content_hash_sha256);
END $workshop_dataset$;

-- ----------------------------------------------------------------------------
-- 2. Evaluation task with the HIDDEN reference labels.
-- One binary finding, as a CLASSIFICATION task with two classes: 0 for
-- absent, 1 for present (decided 2026-11-22). Its result page shows the
-- per-class table: the recall of class 1 is the sensitivity, the recall of
-- class 0 the specificity. The referable threshold is not read by this kind;
-- it is set to 1 so the row stays meaningful if the kind is ever changed.
-- Same rule as the answer key of demo.sql (#464): inserted once, never
-- overwritten, and the seed fails if the stored key differs from this file.
-- The error names item ids only, never a label: migrate logs are printed in
-- the deploy output.
-- Results are also reported by sex and by age band (#410, ADR-0030). The
-- fields and each item's values follow the answer key's rule: written with
-- the task, or once onto a task seeded before they existed, never
-- overwritten, and the seed fails if the stored values differ from this file.
-- ----------------------------------------------------------------------------

DO $workshop_answer_key$
DECLARE
  expected_gt CONSTANT jsonb := ${text(JSON.stringify(answerKey))}::jsonb;
  expected_fields CONSTANT jsonb := ${text(JSON.stringify(subgroupFields()))}::jsonb;
  expected_values CONSTANT jsonb := ${text(JSON.stringify(subgroupValues))}::jsonb;
  stored_gt jsonb;
  stored_fields jsonb;
  stored_values jsonb;
  drifted_ids text;
BEGIN
  INSERT INTO "evaluation"."evaluation_tasks"
      (id, slug, name, dataset_slug, task_kind, num_classes, referable_threshold,
       ground_truth, subgroup_fields, subgroup_values, created_at, updated_at)
  VALUES (
      ${text(uuid5(`${PROFILE}:evaluation-task:${EVALUATION_TASK_SLUG}`))}::uuid,
      ${text(EVALUATION_TASK_SLUG)},
      ${text(evaluationTaskName(selection))},
      ${text(DATASET_SLUG)},
      'CLASSIFICATION'::"evaluation"."EvaluationTaskKind",
      2,
      1,
      expected_gt,
      expected_fields,
      expected_values,
      CURRENT_TIMESTAMP,
      CURRENT_TIMESTAMP
  )
  ON CONFLICT (slug) DO NOTHING;

  -- A task seeded before #410 gets its subgroup fields once.
  UPDATE "evaluation"."evaluation_tasks"
  SET subgroup_fields = expected_fields, subgroup_values = expected_values
  WHERE slug = ${text(EVALUATION_TASK_SLUG)} AND subgroup_values IS NULL;

  SELECT ground_truth INTO stored_gt
  FROM "evaluation"."evaluation_tasks"
  WHERE slug = ${text(EVALUATION_TASK_SLUG)};

  IF stored_gt IS DISTINCT FROM expected_gt THEN
    IF jsonb_typeof(stored_gt) IS DISTINCT FROM 'object' THEN
      RAISE EXCEPTION 'evaluation task %: stored ground_truth is not a JSON object (got %), expected the answer key of the ${PROFILE} seed profile',
        ${text(EVALUATION_TASK_SLUG)}, coalesce(jsonb_typeof(stored_gt), 'NULL');
    END IF;

    SELECT string_agg(item_id, ', ' ORDER BY item_id) INTO drifted_ids
    FROM (
      SELECT coalesce(s.key, e.key) AS item_id
      FROM jsonb_each(stored_gt) AS s
      FULL OUTER JOIN jsonb_each(expected_gt) AS e ON s.key = e.key
      WHERE s.value IS DISTINCT FROM e.value
    ) AS diff;

    RAISE EXCEPTION 'evaluation task %: stored ground_truth differs from the ${PROFILE} seed profile for item ids [%]. Not overwriting; see #464.',
      ${text(EVALUATION_TASK_SLUG)}, drifted_ids;
  END IF;

  -- Same rule for the subgroup fields and values. The error names item ids,
  -- never a value.
  SELECT subgroup_fields, subgroup_values INTO stored_fields, stored_values
  FROM "evaluation"."evaluation_tasks"
  WHERE slug = ${text(EVALUATION_TASK_SLUG)};

  IF stored_fields IS DISTINCT FROM expected_fields THEN
    RAISE EXCEPTION 'evaluation task %: stored subgroup_fields differ from the ${PROFILE} seed profile. Not overwriting; see #410.',
      ${text(EVALUATION_TASK_SLUG)};
  END IF;

  IF stored_values IS DISTINCT FROM expected_values THEN
    IF jsonb_typeof(stored_values) IS DISTINCT FROM 'object' THEN
      RAISE EXCEPTION 'evaluation task %: stored subgroup_values is not a JSON object, expected the item values of the ${PROFILE} seed profile',
        ${text(EVALUATION_TASK_SLUG)};
    END IF;

    SELECT string_agg(item_id, ', ' ORDER BY item_id) INTO drifted_ids
    FROM (
      SELECT coalesce(s.key, e.key) AS item_id
      FROM jsonb_each(stored_values) AS s
      FULL OUTER JOIN jsonb_each(expected_values) AS e ON s.key = e.key
      WHERE s.value IS DISTINCT FROM e.value
    ) AS diff;

    RAISE EXCEPTION 'evaluation task %: stored subgroup_values differ from the ${PROFILE} seed profile for item ids [%]. Not overwriting; see #410.',
      ${text(EVALUATION_TASK_SLUG)}, drifted_ids;
  END IF;
END $workshop_answer_key$;

-- ----------------------------------------------------------------------------
-- 3. Annotation campaign: the reading exercise.
-- READY, not RUNNING: its tasks are created from the dataset's files by a
-- campaign manager once that exists (#646), and READY is the state in which
-- tasks can be loaded before the campaign is started. NO TASK IS CREATED
-- HERE. The ${selection.images.filter((i) => i.campaign).length} images of the reading subset are the ones flagged
-- \`"campaign": true\` in selection.json.
-- taskTimeoutHours is ${TASK_TIMEOUT_HOURS}: an image left open returns to the queue within the
-- session (decision of 17 November 2026 on #644).
-- ----------------------------------------------------------------------------

INSERT INTO "annotation"."annotation_campaigns"
    (id, slug, name, description, status, task_kind, dataset_id, manifest_version_id,
     tool_integration_id, output_license, workflow_config, created_by_id,
     created_at, updated_at, started_at, completed_at)
SELECT
    ${text(uuid5(`${PROFILE}:campaign:${CAMPAIGN_SLUG}`))}::uuid,
    ${text(CAMPAIGN_SLUG)},
    ${text(campaignName(selection))},
    ${text(campaignDescription(selection))},
    'READY'::"annotation"."CampaignStatus",
    'CLASSIFICATION'::"annotation"."CampaignTaskKind",
    ds.id,
    ver.id,
    tool.id,
    'CC-BY-4.0'::"annotation"."CampaignOutputLicense",
    ${text(workflow)}::jsonb,
    ${text(SEED_USER_ID)},
    CURRENT_TIMESTAMP, CURRENT_TIMESTAMP, NULL, NULL
FROM "catalog"."datasets" ds
JOIN "catalog"."dataset_versions" ver
  ON ver.dataset_id = ds.id AND ver.version = ${text(DATASET_VERSION)},
     "annotation"."annotation_tool_integrations" tool
WHERE ds.slug = ${text(DATASET_SLUG)}
  AND tool.slug = 'ohif-viewer'
ON CONFLICT (slug) DO NOTHING;

-- Instructions, in French. The version is the one the API would compute for
-- this text (first 16 hex characters of its sha256).
INSERT INTO "annotation"."annotation_campaign_instructions"
    (campaign_id, version, markdown_body, media_urls, created_by_id)
SELECT c.id, ${text(version)}, ${dollar('instructions', instructions)}, '[]'::jsonb, ${text(SEED_USER_ID)}
FROM "annotation"."annotation_campaigns" c
WHERE c.slug = ${text(CAMPAIGN_SLUG)}
ON CONFLICT (campaign_id, version) DO NOTHING;

-- Point the campaign at them, unless a manager has published their own since:
-- only an empty pointer or one that still names a version this seed wrote is
-- moved.
UPDATE "annotation"."annotation_campaigns" c
SET current_instructions_version = ${text(version)}, updated_at = CURRENT_TIMESTAMP
WHERE c.slug = ${text(CAMPAIGN_SLUG)}
  AND c.current_instructions_version IS DISTINCT FROM ${text(version)}
  AND (
    c.current_instructions_version IS NULL
    OR EXISTS (
      SELECT 1 FROM "annotation"."annotation_campaign_instructions" i
      WHERE i.campaign_id = c.id
        AND i.version = c.current_instructions_version
        AND i.created_by_id = ${text(SEED_USER_ID)}
    )
  );

-- ----------------------------------------------------------------------------
-- 4. Model cards. Fictional teaching entries on the reserved .example domain.
-- The intended-use statement attaches to the model, never to the dataset
-- (ADR-0013). Model A is PUBLISHED with a complete statement; model B is a
-- DRAFT. The JSON follows IntendedUseStatementSchema (@oci/shared-types).
-- ----------------------------------------------------------------------------

INSERT INTO "prediction"."model_cards"
    (id, slug, intended_use, model_class, architecture_summary, version_major_minor_patch,
     training_data_jurisdictions, generative_ai, status, model_developer, developer_contact,
     clinical_summary, known_biases_or_ethical_considerations, ongoing_maintenance, updated_at)
VALUES
${modelCardRow(MODEL_A_SLUG, cards.modelA)},
${modelCardRow(MODEL_B_SLUG, cards.modelB)}
ON CONFLICT (slug) DO NOTHING;

COMMIT;
`;
}
